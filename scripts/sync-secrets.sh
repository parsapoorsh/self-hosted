#!/usr/bin/env bash
# Derive internal service secrets into gitignored .env.secrets.
# Human login uses KEYCLOAK_ADMIN / KEYCLOAK_ADMIN_PASSWORD only.
# Usage: ./scripts/sync-secrets.sh
#        ./scripts/compose.sh up -d   # runs this first
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ROOT}/.env"
OUT_FILE="${ROOT}/.env.secrets"

if [[ ! -f "${ENV_FILE}" ]]; then
  echo "sync-secrets: missing ${ENV_FILE} (copy .env.example)" >&2
  exit 1
fi

# Load user .env without executing it as shell beyond KEY=VAL lines.
set -a
# shellcheck disable=SC1090
source "${ENV_FILE}"
set +a

ADMIN_USER="${KEYCLOAK_ADMIN:-admin}"
ADMIN_PASS="${KEYCLOAK_ADMIN_PASSWORD:-}"
PG_PASS="${POSTGRES_PASSWORD:-}"

if [[ -z "${ADMIN_PASS}" ]]; then
  echo "sync-secrets: KEYCLOAK_ADMIN_PASSWORD is required in .env" >&2
  exit 1
fi
if [[ -z "${PG_PASS}" ]]; then
  echo "sync-secrets: POSTGRES_PASSWORD is required in .env" >&2
  exit 1
fi

# Stable hex material from (seed, label). Prefer sha256sum; fall back to openssl.
derive_hex() {
  local seed="$1"
  local label="$2"
  if command -v sha256sum >/dev/null 2>&1; then
    printf '%s:%s' "${label}" "${seed}" | sha256sum | awk '{print $1}'
  else
    printf '%s:%s' "${label}" "${seed}" | openssl dgst -sha256 | awk '{print $NF}'
  fi
}

# 32-char secret suitable for passwords / client secrets.
derive_pass() {
  derive_hex "$1" "$2" | cut -c1-32
}

# oauth2-proxy cookie secret: 24 raw bytes, base64-encoded.
derive_cookie() {
  local hex
  hex="$(derive_hex "$1" "$2" | cut -c1-48)"
  if command -v xxd >/dev/null 2>&1; then
    printf '%s' "${hex}" | xxd -r -p | base64 -w0 2>/dev/null || printf '%s' "${hex}" | xxd -r -p | base64
  else
    python3 -c "import binascii,base64,sys; print(base64.b64encode(binascii.unhexlify(sys.argv[1])).decode())" "${hex}"
  fi
}

# DB role passwords track POSTGRES_PASSWORD (stable if admin password rotates).
KEYCLOAK_DB_PASSWORD="$(derive_pass "${PG_PASS}" "keycloak-db")"
NEXTCLOUD_DB_PASSWORD="$(derive_pass "${PG_PASS}" "nextcloud-db")"

# OIDC / cookie material tracks the Keycloak admin password.
OIDC_CLIENT_SECRET="$(derive_pass "${ADMIN_PASS}" "oidc-nextcloud")"
NEXUS_OIDC_CLIENT_SECRET="$(derive_pass "${ADMIN_PASS}" "oidc-nexus")"
NEXUS_OAUTH2_COOKIE_SECRET="$(derive_cookie "${ADMIN_PASS}" "nexus-oauth2-cookie")"

# One human admin everywhere.
NEXTCLOUD_ADMIN_USER="${ADMIN_USER}"
NEXTCLOUD_ADMIN_PASSWORD="${ADMIN_PASS}"
NEXUS_ADMIN_USER="${ADMIN_USER}"
NEXUS_ADMIN_PASSWORD="${ADMIN_PASS}"

umask 077
cat >"${OUT_FILE}" <<EOF
# Generated by scripts/sync-secrets.sh — do not commit.
# Source seed: KEYCLOAK_ADMIN_PASSWORD + POSTGRES_PASSWORD from .env

KEYCLOAK_DB_PASSWORD=${KEYCLOAK_DB_PASSWORD}
NEXTCLOUD_DB_PASSWORD=${NEXTCLOUD_DB_PASSWORD}

OIDC_CLIENT_ID=nextcloud
OIDC_CLIENT_SECRET=${OIDC_CLIENT_SECRET}
NEXUS_OIDC_CLIENT_ID=nexus
NEXUS_OIDC_CLIENT_SECRET=${NEXUS_OIDC_CLIENT_SECRET}
NEXUS_OAUTH2_COOKIE_SECRET=${NEXUS_OAUTH2_COOKIE_SECRET}

NEXTCLOUD_ADMIN_USER=${NEXTCLOUD_ADMIN_USER}
NEXTCLOUD_ADMIN_PASSWORD=${NEXTCLOUD_ADMIN_PASSWORD}
NEXUS_ADMIN_USER=${NEXUS_ADMIN_USER}
NEXUS_ADMIN_PASSWORD=${NEXUS_ADMIN_PASSWORD}

KEYCLOAK_REALM=home
EOF

echo "sync-secrets: wrote ${OUT_FILE}"
