#!/bin/sh
# Ensure localhost cert, render templates (__DOMAIN__ -> DOMAIN), start nginx.
set -eu

DOMAIN="${DOMAIN:-example.com}"
SRC="/etc/nginx/self-hosted"
RUNTIME="/etc/nginx/self-hosted-runtime"
CERTS="/etc/nginx/certs"

# Avoid sed specials in domain: only allow simple DNS labels.
case "$DOMAIN" in
  *[!a-zA-Z0-9.-]* | "" | .* | *..* | *- | *-.* )
    echo "invalid DOMAIN: $DOMAIN" >&2
    exit 1
    ;;
esac

mkdir -p "$RUNTIME/snippets"

# --- localhost TLS (first start): cert/localhost/{fullchain,privkey}.pem ---
ensure_localhost_cert() {
  local out="$CERTS/localhost"
  local work days=825

  if [ -f "$out/fullchain.pem" ] && [ -f "$out/privkey.pem" ]; then
    echo "nginx: localhost cert present"
    return 0
  fi

  if [ ! -w "$CERTS" ]; then
    echo "nginx: cert/ not writable; cannot create localhost cert" >&2
    echo "nginx: run ./scripts/self-signed.sh localhost on the host, or mount cert/ rw" >&2
    return 1
  fi

  if ! command -v openssl >/dev/null 2>&1; then
    apk add --no-cache openssl >/dev/null
  fi

  echo "nginx: creating cert/localhost (self-signed)"
  work="$(mktemp -d)"
  mkdir -p "$out"

  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out "$work/ca.key" 2>/dev/null
  openssl req -x509 -new -nodes -key "$work/ca.key" -sha256 -days "$days" \
    -subj "/CN=self-hosted local CA" -out "$work/ca.pem"

  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out "$out/privkey.pem" 2>/dev/null
  chmod 644 "$out/privkey.pem"

  cat >"$work/leaf.cnf" <<EOF
[req]
distinguished_name = req_distinguished_name
req_extensions = v3_req
prompt = no

[req_distinguished_name]
CN = localhost

[v3_req]
basicConstraints = CA:FALSE
keyUsage = digitalSignature
extendedKeyUsage = serverAuth
subjectAltName = @alt_names

[alt_names]
DNS.1 = localhost
DNS.2 = *.localhost
IP.1 = 127.0.0.1
IP.2 = ::1
EOF

  openssl req -new -key "$out/privkey.pem" -config "$work/leaf.cnf" -out "$work/leaf.csr"
  openssl x509 -req -in "$work/leaf.csr" \
    -CA "$work/ca.pem" -CAkey "$work/ca.key" -CAcreateserial \
    -out "$out/cert.pem" -days "$days" -sha256 \
    -extfile "$work/leaf.cnf" -extensions v3_req

  cp "$work/ca.pem" "$out/chain.pem"
  cat "$out/cert.pem" "$out/chain.pem" >"$out/fullchain.pem"
  cp "$work/ca.pem" "$out/ca.pem"
  cp "$work/ca.key" "$out/ca.key"
  chmod 600 "$out/ca.key"
  rm -rf "$work"
  echo "nginx: wrote $out"
}

ensure_localhost_cert

# SNI -> cert directory (primary DOMAIN vs always-on localhost).
cat >"$RUNTIME/snippets/cert-map.conf" <<EOF
# Generated by docker-entrypoint.sh — do not edit.
map \$ssl_server_name \$edge_cert_dir {
    default                 ${CERTS}/${DOMAIN};
    localhost               ${CERTS}/localhost;
    ~\\.localhost\$          ${CERTS}/localhost;
}
# HTTP (no SNI): pick by Host header for any ssl_reject_handshake edge cases.
map \$host \$edge_cert_dir_http {
    default                 ${CERTS}/${DOMAIN};
    localhost               ${CERTS}/localhost;
    ~\\.localhost\$          ${CERTS}/localhost;
}
# Nexus oauth2-proxy: DOMAIN instance vs localhost instance.
map \$host \$nexus_oauth2_upstream {
    default                 http://nexus-oauth2-proxy:4180;
    nexus.localhost         http://nexus-oauth2-local:4180;
    ~^nexus\\.localhost\$    http://nexus-oauth2-local:4180;
}
EOF

# edge-tls is static (uses $edge_cert_dir); copy as-is.
cp "$SRC/snippets/edge-tls.conf" "$RUNTIME/snippets/edge-tls.conf"

sed "s/__DOMAIN__/${DOMAIN}/g" \
  "$SRC/server.conf.template" >"$RUNTIME/server.conf"

# Primary domain cert must exist (operator-provided or self-signed on host).
if [ ! -f "$CERTS/$DOMAIN/fullchain.pem" ] || [ ! -f "$CERTS/$DOMAIN/privkey.pem" ]; then
  echo "nginx: missing cert/${DOMAIN}/{fullchain,privkey}.pem" >&2
  exit 1
fi

echo "nginx DOMAIN=${DOMAIN} + localhost (auth/kiwix/cloud/nexus)"

exec nginx -g "daemon off;" -c /etc/nginx/self-hosted/nginx.conf
